if not neon_db_url:
    env_local = BASE_DIR.parent / '.env.local'
    if env_local.exists():
        with open(env_local, encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line.startswith('DATABASE_URL_UNPOOLED='):
                    neon_db_url = line.split('=', 1)[1].strip().strip('"').strip("'")
